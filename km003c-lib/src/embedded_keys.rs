//! Embedded material recovered from the official client.
//!
//! AES-256-CBC hides plaintext literals in the source and normal build artifacts.
//! The wrapping key ships alongside the ciphertext, so this is obfuscation, not
//! a confidentiality boundary. Each value uses its own IV and zero padding;
//! its exact decoded length is fixed below. No files or network access is needed.

use aes::{
    Aes256,
    cipher::{BlockCipherDecrypt, KeyInit},
};
use std::sync::LazyLock;

const WRAPPING_KEY: [u8; 32] = [
    0xd5, 0xeb, 0x9f, 0x34, 0xa5, 0x48, 0x2b, 0x72, 0xd7, 0x09, 0x94, 0xdc, 0xee, 0x92, 0x16, 0x67, 0xeb, 0xb5, 0xa2,
    0x59, 0xa2, 0x5e, 0x41, 0x8d, 0x8c, 0x93, 0x91, 0x58, 0x82, 0x9a, 0x62, 0x49,
];

// Keep unwrapping at runtime, including in optimized builds.
#[inline(never)]
fn unwrap<const N: usize, const M: usize>(encrypted: &[u8; M], iv: [u8; 16]) -> [u8; N] {
    assert!(M.is_multiple_of(16) && N <= M && M - N < 16);
    let cipher = Aes256::new((&std::hint::black_box(WRAPPING_KEY)).into());
    let mut output = [0; N];
    let mut previous = iv;
    for (index, block) in encrypted.as_chunks::<16>().0.iter().enumerate() {
        let mut decoded = *block;
        cipher.decrypt_block((&mut decoded).into());
        for (byte, mask) in decoded.iter_mut().zip(previous) {
            *byte ^= mask;
        }
        let offset = index * 16;
        let count = (N - offset).min(16);
        output[offset..offset + count].copy_from_slice(&decoded[..count]);
        previous = *block;
    }
    output
}

